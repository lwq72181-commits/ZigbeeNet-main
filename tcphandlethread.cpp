int TCPHandleThread::handle_recv_data(char *buf, int len, int fd)
{
    int i = 0;
    int ret = 0;
    char replay_buf[100] ={0};
    char *p =NULL;
    int handle_len =0;
    int check_data = 0;
    int cmd_len=0;
    //pthread_t heart_beat_id[50];
    //static_handle_beat = 0;
    p = buf;
    while(handle_len<(len-1))
    {
        for (i=0; i<len-handle_len;i++ )
        {
            if(0xff != p[i])
            {
                if(i==(len-handle_len-1))
                {
                    qDebug("recv data text is  wrong!!!\n");
                    return -1;
                }
                else
                {
                    handle_len++;
                    continue;
                }
            }
            else
            {
                p = buf + handle_len;
                cmd_len = check_cmd_data(p);
                if(cmd_len==0 || cmd_len>(len-handle_len))
                {
                    qDebug("cmd len wrong %d\n", cmd_len);
                    handle_len++;
                            continue;

                }
                break;
            }
        }
        i=1;
        switch(p[i])
        {
            case 0x03:
            check_data = judge_ask_data(p, cmd_len);
            if(check_data == 1)
            {
                setSysNetwork(reinterpret_cast<unsigned char*>(&p[10]));
                ret = packReplayBuff(replay_buf,4);
                replay_ask_data(replay_buf, ret, fd);
                handle_len+=cmd_len;
            }
            else
            handle_len++;
            break;
            case 0x05:
            check_data = judge_ask_data(p, cmd_len);
            if(check_data == 1)
            {
                setMqttServer(reinterpret_cast<unsigned char*>(&p[10]));
                ret = packReplayBuff(replay_buf,6);
                replay_ask_data(replay_buf, ret, fd);
                handle_len+=cmd_len;
            }
            else
            handle_len++;
            break;
            case 0x07:
            check_data = judge_ask_data(p, cmd_len);
            if(check_data == 1)
            {
                setMqttInfo(&p[10],cmd_len-10);
                ret = packReplayBuff(replay_buf,8);
                replay_ask_data(replay_buf, ret, fd);
                handle_len+=cmd_len;
            }
            else
            handle_len++;
            break;
            case 0x09:
            check_data = judge_ask_data(p, cmd_len);
            if(check_data == 1)
            {
                setAcquistInfo(&p[10]);
                ret = packReplayBuff(replay_buf,9);
                replay_ask_data(replay_buf, ret, fd);
                handle_len+=cmd_len;
            }
            else
            handle_len++;
            break;
            case 0x0f1:
            check_data = judge_ask_data(p, cmd_len);
            if(check_data == 1)
            {
                ret =replyLocalNetInfo(reinterpret_cast<unsigned char*>(replay_buf));
                replay_ask_data(replay_buf, ret, fd);
                handle_len+=cmd_len;
            }
            else
            handle_len++;
            break;
            case 0xf3:
            check_data = judge_ask_data(p, cmd_len);
            if(check_data == 1)
            {
                //get_extern_state();
                ret =replySNInfo(replay_buf);
                replay_ask_data(replay_buf, ret, fd);
                handle_len+=cmd_len;
            }
            else
            handle_len++;
            break;
            default:
            handle_len+=cmd_len;
            break;
        }
        memset(replay_buf, 0, sizeof(replay_buf));
        p = buf + handle_len;
    }
    return ret;

}

