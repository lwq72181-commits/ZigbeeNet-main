int TCPHandleThread::check_cmd_data(char *cmd)
{
    int ret = 0;
    switch(cmd[1])
    {
        case 3:
        if(cmd[3]==0)
            ret = 10;
        else if(cmd[3]==0xf1)
            ret = 26;
        break;
        case 5:
        if(cmd[3]==6)
            ret = 16;
        break;
        case 7:
        ret = (cmd[4]<<8)|cmd[3]+10;
        break;
        case 9:
        if(cmd[3]==6)
            ret = 16;
        break;
        case 0xf1:
        if(cmd[3]==0)
            ret = 10;
        break;
        case 0xf3:
        if(cmd[3]==0)
            ret = 10;
        break;
        default:
        break;
    }
    return ret;
}

