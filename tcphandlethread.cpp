int TCPHandleThread::replay_ask_data(char *replay_buf, int len, int fd)
{
    int senddata = len;
    int real_send = 0;
    int ret = 0;
    qDebug("replay data: ");
    for(int i=0; i<len; i++)
    {
        qDebug("%02x ", replay_buf[i]);
    }
    while(senddata != 0)
    {
        ret = send(fd, replay_buf + real_send, senddata, 0);
        if(ret == -1 || ret == 0) return -1;
        senddata -= ret;
        real_send += ret;
    }
    return 0;
}

